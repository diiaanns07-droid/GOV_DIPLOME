"""Нормализация текста для поиска похожих обращений (только стандартная библиотека).

Задача — чтобы один и тот же смысл, написанный по-разному, давал одинаковые строки:
  - регистр, «ё» -> «е», пунктуация и цифры (номер дома не должен «склеивать» разные жалобы);
  - маркеры обезличивания R02 ([телефон], [адрес], <phone> …) убираются;
  - латиница из чатов («yama na doroge», «aialdamada») переводится в кириллицу;
  - казахские буквы сводятся к русским двойникам (қ -> к, ү -> у, і -> и …), поэтому
    казахский текст, набранный без специфических букв («кар», «аялдама»), совпадает с правильным.
Сводка теряет различие «қ/к», но для поиска дублей это допустимо: решает не одна буква, а набор слов.
"""

from __future__ import annotations

import re
import unicodedata

# Казахские буквы -> ближайшая русская (как набирают без казахской раскладки).
KK_FOLD = str.maketrans({
    "ә": "а", "ғ": "г", "қ": "к", "ң": "н", "ө": "о", "ұ": "у", "ү": "у", "һ": "х", "і": "и", "ё": "е",
    "й": "и",  # «тазаланбайды» и транслит «tazalanbaidy» должны совпасть
})
# Разные апострофы из телефонных клавиатур -> один.
_APOSTROPHES = str.maketrans({"’": "'", "ʼ": "'", "`": "'", "´": "'", "‘": "'"})

# Латиница -> кириллица. Сначала длинные сочетания, потом одиночные буквы.
# Покрывает привычный русский транслит (sh, zh, ch, ya) и казахскую латиницу 2017–2021 гг.
# (ä, ğ, q, ñ, ö, ū, ü, ı, ş, ç и апострофные a', g', o', u', n', s', c'). Казахские звуки
# переводятся в казахские буквы (q -> қ, ğ -> ғ): словари классификаторов написаны с ними.
_LAT_MULTI = (
    ("shch", "щ"), ("sch", "щ"), ("zh", "ж"), ("kh", "х"), ("ts", "ц"), ("ch", "ч"), ("sh", "ш"),
    ("ya", "я"), ("ia", "я"), ("yu", "ю"), ("iu", "ю"), ("yo", "ё"), ("ye", "е"),
    ("ay", "ай"), ("ey", "ей"), ("oy", "ой"), ("uy", "уй"), ("iy", "ий"), ("ai", "ай"), ("ei", "ей"), ("oi", "ой"),
    ("a'", "ә"), ("g'", "ғ"), ("o'", "ө"), ("u'", "ү"), ("n'", "ң"), ("s'", "ш"), ("c'", "ч"), ("i'", "і"),
)
_LAT_SINGLE = {
    "a": "а", "b": "б", "c": "с", "d": "д", "e": "е", "f": "ф", "g": "г", "h": "х", "i": "и", "j": "ж",
    "k": "к", "l": "л", "m": "м", "n": "н", "o": "о", "p": "п", "q": "қ", "r": "р", "s": "с", "t": "т",
    "u": "у", "v": "в", "w": "у", "x": "кс", "y": "ы", "z": "з",
    "ä": "ә", "ğ": "ғ", "ı": "ы", "ñ": "ң", "ö": "ө", "ş": "ш", "ç": "ч", "ü": "ү", "ū": "ұ", "é": "е",
}
# «ai/ay…» = «ай» только перед согласной или в конце слова: «aialdama» -> «аялдама» (a + ia), а не «айалдама».
_DIPHTHONGS = {"ay", "ey", "oy", "uy", "iy", "ai", "ei", "oi"}
_LAT_RE = re.compile("|".join(re.escape(k) + ("(?![aeiouyäöüıū])" if k in _DIPHTHONGS else "")
                              for k, _ in _LAT_MULTI) + "|[a-zäğıñöşçüūé]")
_LAT_MAP = dict(_LAT_MULTI) | _LAT_SINGLE
_LATIN_LETTER = re.compile(r"[a-zäğıñöşçüūé]")

# Маркеры обезличивания: R02 ([телефон], [адрес]) и v1 (<phone>, <url>).
_MARKER = re.compile(r"\[[^\[\]]{1,24}\]|<[a-z]{2,8}>")
_URL = re.compile(r"(?:https?://|www\.)\S+")
_NON_WORD = re.compile(r"[^\w\s]")
_DIGITS = re.compile(r"\d+")
_SPACE = re.compile(r"\s+")


def detranslit(text: str) -> str:
    """Латинские буквы -> кириллица (текст уже в нижнем регистре). Кириллица не меняется."""
    return _LAT_RE.sub(lambda m: _LAT_MAP[m.group(0)], text)


def to_cyrillic(text: str, *, min_share: float = 0.5) -> str:
    """Для классификатора: если латиницы среди букв ≥ min_share (чат-транслит), переводим в кириллицу.

    Текст в основном кириллический (с «Wi-Fi», «Onay» внутри) не трогаем. Результат в нижнем регистре —
    классификаторы v1/v2 и словарь всё равно приводят текст к нему.
    """
    t = unicodedata.normalize("NFC", str(text))
    low = t.casefold().translate(_APOSTROPHES)
    n_letters = sum(ch.isalpha() for ch in low)
    if not n_letters or len(_LATIN_LETTER.findall(low)) < min_share * n_letters:
        return t
    return detranslit(low)


def normalize(text: str) -> str:
    """Строка для сравнения: нижний регистр, без маркеров, пунктуации и цифр, кириллица, без казахских букв."""
    t = unicodedata.normalize("NFC", str(text)).casefold().translate(_APOSTROPHES)
    t = _URL.sub(" ", t)
    t = _MARKER.sub(" ", t)
    t = detranslit(t)  # до удаления пунктуации: казахская латиница 2017 г. пишет «s'» = «ш»
    t = t.replace("_", " ")
    t = _NON_WORD.sub(" ", t)
    t = _DIGITS.sub(" ", t)
    t = t.translate(KK_FOLD)
    return _SPACE.sub(" ", t).strip()


def letters(text: str) -> int:
    """Число букв — чтобы отличить осмысленный текст от «...» или «123»."""
    return sum(ch.isalpha() for ch in str(text))
