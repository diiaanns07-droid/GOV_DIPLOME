# Понятия-места: где проблема, а не какая. Место уже проверяет геофильтр (≤ 200 м / та же цель),
# поэтому общее «на остановке» почти не добавляет сходства: «снег на остановке» ≠ «скамейка на остановке».
# Вес не ноль: если в текстах только место («Аялдама жөнделмейді» / «Остановку не ремонтируют»), оно и решает.
PLACE_WEIGHT = 0.3
PLACE_CONCEPTS = frozenset({"bus_stop", "sidewalk", "playground", "sports_ground", "crossing"})


def weight(concept: str) -> float:
    return PLACE_WEIGHT if concept in PLACE_CONCEPTS else 1.0


@lru_cache(maxsize=1)
def _compiled() -> tuple[tuple[str, str], ...]:
    """(основа после normalize с ведущим пробелом, понятие). Основа с пробелом в конце — целое слово."""
    out = []
    for concept, stems in CONCEPTS.items():
        for stem in stems:
            whole_word = stem.endswith(" ")
            norm = normalize(stem)
            if not norm:
                continue
            out.append((" " + norm + (" " if whole_word else ""), concept))
    return tuple(out)


def concepts(normalized_text: str) -> frozenset[str]:
    """Понятия, найденные в тексте. Текст уже должен быть после normalize()."""
    t = " " + normalized_text + " "
    return frozenset(concept for stem, concept in _compiled() if stem in t)
