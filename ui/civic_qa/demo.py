def rows(now: datetime) -> list[dict]:
    out = []
    for qid, district, lang, text, votes, ago in _PUBLISHED:
        out.append({"id": qid, "district": district, "lang": lang, "text": text, "status": "published",
                    "created_at": iso(now - ago - 2 * H), "published_at": iso(now - ago), "base_votes": votes})
    for qid, district, lang, text, votes, ago, ans_ru, ans_kk, ans_ago in _ANSWERED:
        out.append({"id": qid, "district": district, "lang": lang, "text": text, "status": "published",
                    "created_at": iso(now - ago - 2 * H), "published_at": iso(now - ago), "base_votes": votes,
                    "answer_ru": ans_ru, "answer_kk": ans_kk, "answered_at": iso(now - ans_ago)})
    for qid, district, lang, text, ago in _PENDING:
        out.append({"id": qid, "district": district, "lang": lang, "text": text, "status": "pending",
                    "created_at": iso(now - ago)})
    return out
