_EXTRA_FORMS = frozenset(
    word for forms in _KK_CARDINALS.values() for word in forms.split()
) | frozenset(_KK_OTHER) | frozenset(_RU_EXTRA)
_WORD = re.compile(r"\w+", re.UNICODE)


def extra_numeral(text: str) -> str | None:
    """Первая найденная словоформа из расширения или None."""
    for token in _WORD.findall(text.casefold()):
        if token in _EXTRA_FORMS:
            return token
    return None


def is_numeric(part: str) -> bool:
    """Текущее правило agent/evidence.py плюс расширение K02."""
    current = (any(char.isnumeric() for char in part) or NUMBER_WORDS.search(part)
               or "{{" in part or "}}" in part)
    return bool(current or extra_numeral(part))


def qualitative_comment_v2(draft: str, *, saray_shyk_modeled: bool = False) -> tuple[str, bool]:
    """Копия логики qualitative_comment с расширенным признаком числа."""
    if not isinstance(draft, str) or not draft.strip():
        raise EvidenceError("Пустой комментарий.")
    kept, omitted = [], False
    for part in re.split(r"(?<=[.!?])\s+|\n+", draft.strip()):
        if not part.strip():
            continue
        unmodeled = not saray_shyk_modeled and mentions_saray_shyk(part)
        if is_numeric(part) or unmodeled:
            omitted = True
            continue
        kept.append(part.strip())
    comment = "\n".join(kept).strip()
    # Текущая проверка «есть ли текст» требует [А-Яа-яA-Za-z]{3}: казахские ә/ғ/қ/ң/ө/ұ/ү/һ/і
    # в этот класс не входят. Здесь используется любой буквенный символ.
    if not comment or not re.search(r"[^\W\d_]{3}", comment):
        raise EvidenceError("Нет качественного комментария без чисел.")
    return comment, omitted
