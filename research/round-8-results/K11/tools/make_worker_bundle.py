"""K11 round 8: inline the worker sources for Blob-URL workers (file:// pages) and the example's fixture data.

    python tools/make_worker_bundle.py        (from research/round-8-results/K11)

example/worker_bundle.js : window.CITY_PLAN_WORKER_SOURCES = [plan_core.js, plan_worker.js] as strings, with the
                           sha256 of each source so tests can detect a stale bundle.
example/fixture_data.js  : window.K11_EXAMPLE = selected fixtures (context + scenario + provenance), loaded with a
                           plain <script> tag because fetch()/XHR of local files is blocked on file:// pages.
Output is written as bytes (UTF-8, LF), independent of the OS code page.
"""
from __future__ import annotations

import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
EXAMPLE_FIXTURES = [("synthetic", "syn_bench_16x25.json"), ("real", "real_shymkent_school_16x25.json"),
                    ("real", "real_astana_school_16x25.json"), ("real", "real_astana_outpatient_clinic_8x12.json"),
                    ("synthetic", "syn_infeasible_budget.json"), ("synthetic", "syn_unicode_ids.json")]


def main():
    srcs = [ROOT / "src" / "plan_core.js", ROOT / "src" / "plan_worker.js"]
    texts = [p.read_bytes().decode("utf-8") for p in srcs]
    shas = {p.name: hashlib.sha256(p.read_bytes()).hexdigest() for p in srcs}
    out = ROOT / "example"
    out.mkdir(exist_ok=True)
    bundle = ("// GENERATED by tools/make_worker_bundle.py — do not edit. Sources: " + json.dumps(shas) + "\n"
              "window.CITY_PLAN_WORKER_SOURCES = " + json.dumps(texts, ensure_ascii=True) + ";\n"
              "window.CITY_PLAN_WORKER_SOURCES_SHA256 = " + json.dumps(shas) + ";\n")
    (out / "worker_bundle.js").write_bytes(bundle.encode("utf-8"))
    data = {}
    for d, f in EXAMPLE_FIXTURES:
        fx = json.loads((ROOT / "fixtures" / d / f).read_bytes().decode("utf-8"))
        data[f] = {"provenance": fx["provenance"], "context": fx["context"], "scenario": fx["scenario"]}
    js = ("// GENERATED by tools/make_worker_bundle.py from fixtures/ — do not edit.\n"
          "window.K11_EXAMPLE = " + json.dumps(data, ensure_ascii=False, allow_nan=False) + ";\n")
    (out / "fixture_data.js").write_bytes(js.encode("utf-8"))
    print("example/worker_bundle.js", shas)
    print("example/fixture_data.js", len(data), "fixtures")


if __name__ == "__main__":
    main()
